STEP_ON = "background: var(--glow); border-color: #f4cfb8;"
STEP_OFF = "background: transparent; border-color: transparent;"
NUM_ON = "background: var(--accent); color: #fff;"
NUM_OFF = "background: var(--pill-bg); color: var(--muted);"


def p(v):
    return f"{v:g}%"


def window(name, a, b, on, off, fade=1.5, off_in=None):
    """`on` between a..b, `off` elsewhere; fades over `fade` %. off_in = style while fading in."""
    off_in = off_in or off
    frames = []
    if a <= 0:
        frames.append(f"0%, {p(b)} {{ {on} }}")
    else:
        frames.append(f"0%, {p(max(a - fade, 0))} {{ {off_in} }}")
        frames.append(f"{p(a)}, {p(min(b, 100))} {{ {on} }}")
    if b < 100:
        frames.append(f"{p(min(b + fade, 100))}, 100% {{ {off} }}")
    return f"@keyframes {name} {{ {' '.join(frames)} }}"


def steps(prefix, spans):
    out = []
    for i, (a, b) in enumerate(spans, 1):
        out.append(window(f"{prefix}-step{i}", a, b, STEP_ON, STEP_OFF, fade=1))
        out.append(window(f"{prefix}-num{i}", a, b, NUM_ON, NUM_OFF, fade=1))
    return out


def show(name, a, b, fade=1):
    return window(name, a, b, "opacity: 1;", "opacity: 0;", fade=fade)


def pop(name, a, b):
    return window(name, a, b, "opacity: 1; transform: none;", "opacity: 0;", fade=2,
                  off_in="opacity: 0; transform: translateY(6px) scale(0.92);")


def ring(name, a, b):
    return window(name, a, b, "opacity: 1; transform: none;", "opacity: 0;", fade=2,
                  off_in="opacity: 0; transform: scale(1.05);")


def scene(name, a, b, fade=3, zoom_end=None):
    on_end = f"opacity: 1; transform: scale({zoom_end});" if zoom_end else "opacity: 1; transform: none;"
    frames = []
    if a <= 0:
        frames.append(f"0% {{ opacity: 0; transform: translateX(14px); }}")
        frames.append(f"{p(fade)} {{ opacity: 1; transform: none; }}")
    else:
        frames.append(f"0%, {p(a - fade)} {{ opacity: 0; transform: translateX(14px); }}")
        frames.append(f"{p(a)} {{ opacity: 1; transform: none; }}")
    frames.append(f"{p(b - fade)} {{ {on_end} }}")
    frames.append(f"{p(b)}, 100% {{ opacity: 0; transform: {'scale(%s)' % zoom_end if zoom_end else 'translateX(-14px)'}; }}")
    return f"@keyframes {name} {{ {' '.join(frames)} }}"


def cursor(name, path):
    """path: list of (pct, left, top, visible)."""
    frames = []
    for pct, x, y, vis in path:
        frames.append(f"{p(pct)} {{ opacity: {1 if vis else 0}; left: {x}%; top: {y}%; }}")
    return f"@keyframes {name} {{ {' '.join(frames)} }}"


def clicks(name, times):
    frames = ["0% { opacity: 0; transform: scale(0.3); }"]
    for t in times:
        frames.append(f"{p(t - 0.5)} {{ opacity: 0; transform: scale(0.3); }}")
        frames.append(f"{p(t)} {{ opacity: 1; transform: scale(0.4); }}")
        frames.append(f"{p(t + 2.5)} {{ opacity: 0; transform: scale(1.6); }}")
    frames.append("100% { opacity: 0; transform: scale(1.6); }")
    return f"@keyframes {name} {{ {' '.join(frames)} }}"


